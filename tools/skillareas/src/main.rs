//! skillareas: the area each ground skill covers, from rAthena's skill_db, for the client's
//! aiming preview (crates/ro-client/src/skillarea.rs).
//!
//!   skillareas <rathena-dir> [out.rs]
//!
//! Reads db/re/skill_db.yml, with db/import/skill_db.yml over it, and writes
//! crates/ro-client/src/skillarea_db.rs. For every skill with `TargetType: Ground`, each
//! level's radius in cells is what the server covers:
//!   - skills that place units: the unit layout's radius, plus each unit's `Range` when the
//!     units fire on an `Interval` (the server then hits what is within range of every unit
//!     cell, skill_unit_timer_sub), or the `SplashArea` if larger (a trap's blast);
//!   - other ground skills: the `SplashArea`.
//! Layouts the server builds in code (`Layout: -1`: Fire Wall, Sanctuary...) are listed apart
//! with their units' range; the client knows their shapes.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use anyhow::Context;
use yaml_rust2::{Yaml, YamlLoader};

fn main() -> anyhow::Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let rathena = PathBuf::from(args.first().context("usage: skillareas <rathena-dir> [out.rs]")?);
    let out = args.get(1).map(PathBuf::from).unwrap_or_else(|| PathBuf::from("crates/ro-client/src/skillarea_db.rs"));

    // Skills by id: each a map of its fields; the import file's fields replace the base's.
    let mut skills: BTreeMap<i64, yaml_rust2::yaml::Hash> = BTreeMap::new();
    for file in ["db/re/skill_db.yml", "db/import/skill_db.yml"] {
        let path = rathena.join(file);
        let Ok(text) = std::fs::read_to_string(&path) else { continue };
        let docs = YamlLoader::load_from_str(&text).with_context(|| format!("parse {}", path.display()))?;
        let Some(body) = docs.first().and_then(|d| d["Body"].as_vec()) else { continue };
        for entry in body {
            let (Some(id), Some(fields)) = (entry["Id"].as_i64(), entry.as_hash()) else { continue };
            let skill = skills.entry(id).or_default();
            for (k, v) in fields {
                skill.insert(k.clone(), v.clone());
            }
        }
    }

    let mut squares = vec![];
    let mut special = vec![];
    for (id, s) in &skills {
        let s = Yaml::Hash(s.clone());
        if s["TargetType"].as_str() != Some("Ground") {
            continue;
        }
        let name = s["Name"].as_str().unwrap_or("?").to_string();
        let unit = &s["Unit"];
        let levels = (s["MaxLevel"].as_i64().unwrap_or(1)).max(last_level(&unit["Layout"])).max(last_level(&unit["Range"])).max(last_level(&s["SplashArea"]));
        let mut radii: Vec<i64> = vec![];
        let mut is_special = false;
        for lv in 1..=levels {
            let layout = per_level(&unit["Layout"], "Size", lv).unwrap_or(0);
            // Units without an interval act on their own cell only.
            let ticks = unit["Interval"].as_i64().unwrap_or(0) != -1;
            let range = if ticks { per_level(&unit["Range"], "Size", lv).unwrap_or(0).max(0) } else { 0 };
            let splash = per_level(&s["SplashArea"], "Area", lv).unwrap_or(0).max(0);
            if layout == -1 {
                is_special = true;
                radii.push(range);
            } else if unit.is_badvalue() {
                radii.push(splash);
            } else {
                radii.push((layout.max(0) + range).max(splash));
            }
        }
        // The last level repeats: drop the copies.
        while radii.len() > 1 && radii[radii.len() - 1] == radii[radii.len() - 2] {
            radii.pop();
        }
        let radii: Vec<u8> = radii.into_iter().map(|r| r.clamp(0, 255) as u8).collect();
        if is_special {
            special.push((*id, name, radii));
        } else {
            squares.push((*id, name, radii));
        }
    }

    let mut rs = String::new();
    writeln!(rs, "//! Generated by tools/skillareas from rAthena's db/re/skill_db.yml (+ db/import). Do not edit.")?;
    writeln!(rs, "//! Each ground skill's radius in cells per level (the last level repeats); see skillarea.rs.")?;
    writeln!(rs)?;
    writeln!(rs, "/// Square areas: (skill, radius per level).")?;
    writeln!(rs, "pub const SQUARES: &[(u16, &[u8])] = &[")?;
    for (id, name, radii) in &squares {
        writeln!(rs, "    ({id}, &{radii:?}), // {name}")?;
    }
    writeln!(rs, "];")?;
    writeln!(rs)?;
    writeln!(rs, "/// Layouts the server builds in code: (skill, its units' range per level).")?;
    writeln!(rs, "pub const SPECIAL: &[(u16, &[u8])] = &[")?;
    for (id, name, radii) in &special {
        writeln!(rs, "    ({id}, &{radii:?}), // {name}")?;
    }
    writeln!(rs, "];")?;
    std::fs::write(&out, rs).with_context(|| format!("write {}", out.display()))?;
    println!("{} square, {} special ground skills -> {}", squares.len(), special.len(), out.display());
    Ok(())
}

/// A value that is either one number for every level or a list of `{ Level, <key> }`
/// (levels not listed keep the one before).
fn per_level(v: &Yaml, key: &str, level: i64) -> Option<i64> {
    if let Some(n) = v.as_i64() {
        return Some(n);
    }
    let list = v.as_vec()?;
    let at = |e: &Yaml| (e["Level"].as_i64().unwrap_or(0), e[key].as_i64());
    list.iter().map(at).filter(|(l, _)| *l <= level).max_by_key(|(l, _)| *l).or_else(|| list.first().map(at)).and_then(|(_, n)| n)
}

/// The highest level a per-level list names (1 for a single value).
fn last_level(v: &Yaml) -> i64 {
    v.as_vec().map_or(1, |l| l.iter().filter_map(|e| e["Level"].as_i64()).max().unwrap_or(1))
}
