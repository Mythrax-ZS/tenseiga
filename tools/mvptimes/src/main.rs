//! mvptimes: where each boss monster spawns and how long it takes to come back, from the
//! server's NPC scripts, for the client's MVP timers (crates/ro-client/src/mvptimers.rs).
//!
//!   mvptimes <rathena-dir> [out.rs]
//!
//! Follows the scripts the map-server loads (renewal): npc/re/scripts_main.conf and what it
//! imports, plus the `npc:` lines of conf/map_athena.conf and its imports, with `delnpc:`
//! taking files out again. In those, every `boss_monster` line
//! (`map,x,y,xs,ys<TAB>boss_monster<TAB>Name<TAB>id,amount,delay1,delay2,...`) gives a
//! spawn: the server brings it back delay1 plus up to delay2 ms after it dies
//! (mob_setdelayspawn), scaled by battle conf's boss_spawn_delay (conf/battle/monster.conf,
//! then conf/import/battle_conf.txt). Writes crates/ro-client/src/mvptimes_db.rs.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::Context;

fn main() -> anyhow::Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let rathena = PathBuf::from(args.first().context("usage: mvptimes <rathena-dir> [out.rs]")?);
    let out = args.get(1).map(PathBuf::from).unwrap_or_else(|| PathBuf::from("crates/ro-client/src/mvptimes_db.rs"));

    let mut files = Files::default();
    files.conf(&rathena, "npc/re/scripts_main.conf");
    files.conf(&rathena, "conf/map_athena.conf");
    let mut spawns = BTreeSet::new();
    for file in &files.npc {
        let Ok(bytes) = std::fs::read(rathena.join(file)) else { continue };
        spawns.extend(boss_spawns(&String::from_utf8_lossy(&bytes)));
    }
    let rate = battle_setting(&rathena, "boss_spawn_delay").unwrap_or(100);

    let mut rs = String::new();
    writeln!(rs, "//! Generated by tools/mvptimes from the server's NPC scripts (boss_monster lines). Do not edit.")?;
    writeln!(rs, "//! Regenerate with `cargo run -p mvptimes -- <rathena-dir>`; read through mvptimers.rs.")?;
    writeln!(rs)?;
    writeln!(rs, "/// battle conf boss_spawn_delay: the delays below are scaled by it (percent).")?;
    writeln!(rs, "pub const BOSS_SPAWN_DELAY: u32 = {rate};")?;
    writeln!(rs)?;
    writeln!(rs, "/// (map, monster id, base respawn ms, random extra up to ms), by map then monster.")?;
    writeln!(rs, "pub const SPAWNS: &[(&str, u16, u32, u32)] = &[")?;
    for s in &spawns {
        writeln!(rs, "    ({:?}, {}, {}, {}), // {}", s.map, s.mob, s.delay1, s.delay2, s.name)?;
    }
    writeln!(rs, "];")?;
    std::fs::write(&out, rs).with_context(|| format!("write {}", out.display()))?;
    println!("{} boss spawns from {} script files (boss_spawn_delay {rate}) -> {}", spawns.len(), files.npc.len(), out.display());
    Ok(())
}

#[derive(PartialEq, Eq, PartialOrd, Ord, Debug)]
struct Spawn {
    map: String,
    mob: u16,
    delay1: u32,
    delay2: u32,
    name: String,
}

/// The script files the server loads, in order, without the ones taken out.
#[derive(Default)]
struct Files {
    npc: Vec<String>,
    seen: BTreeSet<String>,
}

impl Files {
    fn conf(&mut self, root: &Path, path: &str) {
        if !self.seen.insert(path.to_string()) {
            return;
        }
        let Ok(text) = std::fs::read_to_string(root.join(path)) else { return };
        for line in text.lines() {
            let line = line.trim();
            if line.starts_with("//") {
                continue;
            }
            let Some((key, value)) = line.split_once(':') else { continue };
            let value = value.trim().to_string();
            match key.trim() {
                "import" => self.conf(root, &value),
                "npc" if !self.npc.contains(&value) => self.npc.push(value),
                "delnpc" => self.npc.retain(|f| *f != value),
                _ => {}
            }
        }
    }
}

/// The `boss_monster` spawns in a script.
fn boss_spawns(text: &str) -> Vec<Spawn> {
    let mut out = vec![];
    for line in text.lines() {
        if line.trim_start().starts_with("//") {
            continue;
        }
        let parts: Vec<&str> = line.split('\t').collect();
        let [place, kind, name, params, ..] = parts[..] else { continue };
        if kind.trim() != "boss_monster" {
            continue;
        }
        let map = place.split(',').next().unwrap_or("").trim();
        let nums: Vec<i64> = params.split(',').map(|n| n.trim().parse().unwrap_or(0)).collect();
        let (Some(&mob), Some(&delay1)) = (nums.first(), nums.get(2)) else { continue };
        let Ok(mob) = u16::try_from(mob) else { continue };
        if map.is_empty() || delay1 <= 0 {
            continue;
        }
        let delay2 = nums.get(3).copied().unwrap_or(0).max(0);
        let name = name.split("::").next().unwrap_or(name).trim().to_string();
        out.push(Spawn { map: map.to_string(), mob, delay1: delay1 as u32, delay2: delay2 as u32, name });
    }
    out
}

/// A battle conf setting: conf/import/battle_conf.txt over conf/battle/*.conf.
fn battle_setting(root: &Path, key: &str) -> Option<u32> {
    let read = |path: PathBuf| -> Option<u32> {
        let text = std::fs::read_to_string(path).ok()?;
        text.lines().filter(|l| !l.trim_start().starts_with("//")).filter_map(|l| l.split_once(':')).filter(|(k, _)| k.trim() == key).filter_map(|(_, v)| v.trim().parse().ok()).last()
    };
    read(root.join("conf/import/battle_conf.txt")).or_else(|| read(root.join("conf/battle/monster.conf")))
}

#[cfg(test)]
mod tests {
    use super::boss_spawns;

    #[test]
    fn reads_boss_monster_lines_only() {
        let text = "prt_maze03,0,0,0,0\tboss_monster\tBaphomet\t1039,1,7200000,600000,1\n\
                    prt_maze03,0,0,0,0\tmonster\tBaphomet Jr.\t1101,10,0,0,0\n\
                    //gef_fild10,0,0\tboss_monster\tOrc Lord\t1190,1,7200000,600000,1\n\
                    pay_dun04,0,0\tboss_monster\tEddga::EDDGA\t1115,1,7200000,600000\n";
        let s = boss_spawns(text);
        assert_eq!(s.len(), 2);
        assert_eq!((s[0].map.as_str(), s[0].mob, s[0].delay1, s[0].delay2), ("prt_maze03", 1039, 7200000, 600000));
        assert_eq!(s[1].name, "Eddga");
    }
}
