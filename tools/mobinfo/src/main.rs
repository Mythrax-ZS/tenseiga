//! mobinfo: each monster's level, element, race, size and rank, from the server's mob_db,
//! for the client's monster info on hover (crates/ro-client/src/mobinfo.rs).
//!
//!   mobinfo <rathena-dir> [out.rs]
//!
//! Reads db/mob_db.yml and the files it imports, in its order (renewal ones, not
//! pre-renewal; custom monsters such as db/custom/samurai/mob_db.yml included), each entry's
//! fields replacing the ones before it, as the server loads them. Writes
//! crates/ro-client/src/mobinfo_db.rs.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use anyhow::Context;

const ELEMENTS: [&str; 10] = ["Neutral", "Water", "Earth", "Fire", "Wind", "Poison", "Holy", "Dark", "Ghost", "Undead"];
const RACES: [&str; 10] = ["Formless", "Undead", "Brute", "Plant", "Insect", "Fish", "Demon", "Demihuman", "Angel", "Dragon"];
const SIZES: [&str; 3] = ["Small", "Medium", "Large"];

fn main() -> anyhow::Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let rathena = PathBuf::from(args.first().context("usage: mobinfo <rathena-dir> [out.rs]")?);
    let out = args.get(1).map(PathBuf::from).unwrap_or_else(|| PathBuf::from("crates/ro-client/src/mobinfo_db.rs"));

    // Each monster's fields; a later file's entry replaces the fields it names.
    let mut mobs: BTreeMap<u16, BTreeMap<String, String>> = BTreeMap::new();
    let mut files = vec![];
    for path in imports(&rathena)? {
        let text = std::fs::read_to_string(rathena.join(&path)).with_context(|| format!("read {path}"))?;
        let entries = entries(&text);
        files.push(format!("{path} ({})", entries.len()));
        for (id, fields) in entries {
            mobs.entry(id).or_default().extend(fields);
        }
    }

    let mut rs = String::new();
    writeln!(rs, "//! Generated by tools/mobinfo from the server's db/mob_db.yml and its imports. Do not edit.")?;
    writeln!(rs, "//! Regenerate with `cargo run -p mobinfo -- <rathena-dir>`; read through mobinfo.rs.")?;
    writeln!(rs)?;
    writeln!(rs, "/// (monster id, level, element, element level, race, size, rank), by id. Element, race and")?;
    writeln!(rs, "/// size are rAthena's order (mobinfo.rs names them); rank 0 normal, 1 boss, 2 MVP.")?;
    writeln!(rs, "pub const MOBS: &[(u16, u16, u8, u8, u8, u8, u8)] = &[")?;
    let mut count = 0;
    for (id, m) in &mobs {
        let text = |key: &str| m.get(key).map(String::as_str);
        let num = |key: &str, default: i64| text(key).and_then(|v| v.parse::<i64>().ok()).unwrap_or(default);
        let pick = |key: &str, names: &[&str]| text(key).and_then(|s| names.iter().position(|n| n.eq_ignore_ascii_case(s))).unwrap_or(0);
        let level = num("Level", 1).clamp(0, u16::MAX as i64);
        let element = pick("Element", &ELEMENTS);
        let element_level = num("ElementLevel", 1).clamp(1, 4);
        let race = pick("Race", &RACES);
        let size = pick("Size", &SIZES);
        let mvp = num("MvpExp", 0) > 0 || text("Modes.Mvp") == Some("true");
        let boss = text("Class").is_some_and(|c| c.eq_ignore_ascii_case("Boss"));
        let rank = if mvp { 2 } else if boss { 1 } else { 0 };
        let name = text("AegisName").unwrap_or("?");
        writeln!(rs, "    ({id}, {level}, {element}, {element_level}, {race}, {size}, {rank}), // {name}")?;
        count += 1;
    }
    writeln!(rs, "];")?;
    std::fs::write(&out, rs).with_context(|| format!("write {}", out.display()))?;
    println!("{count} monsters from {} -> {}", files.join(", "), out.display());
    Ok(())
}

/// The files db/mob_db.yml imports, in order: those for renewal or for either mode.
fn imports(rathena: &Path) -> anyhow::Result<Vec<String>> {
    let root = std::fs::read_to_string(rathena.join("db/mob_db.yml")).context("read db/mob_db.yml")?;
    let mut list: Vec<(String, Option<String>)> = vec![];
    for line in root.lines() {
        if let Some(path) = line.trim_start().strip_prefix("- Path:") {
            list.push((path.trim().to_string(), None));
        } else if let (Some(mode), Some(last)) = (line.trim_start().strip_prefix("Mode:"), list.last_mut()) {
            last.1 = Some(mode.trim().to_string());
        }
    }
    anyhow::ensure!(!list.is_empty(), "db/mob_db.yml has no imports");
    Ok(list
        .into_iter()
        .filter(|(_, mode)| mode.as_deref().is_none_or(|m| m.eq_ignore_ascii_case("Renewal")))
        .map(|(path, _)| path)
        .filter(|p| rathena.join(p).exists())
        .collect())
}

/// The monsters in a mob_db file: their top-level fields (`Level`, `Element`...) and the
/// fields of `Modes` (as `Modes.Mvp`), by id. Read by line, as rAthena writes these files
/// (a full YAML parser trips over duplicated keys in the stock db): entries start at
/// `  - Id:`, fields are indented four spaces, a section's own fields six.
fn entries(text: &str) -> Vec<(u16, BTreeMap<String, String>)> {
    let mut out: Vec<(u16, BTreeMap<String, String>)> = vec![];
    let mut section = String::new();
    for line in text.lines() {
        if line.trim_start().starts_with('#') {
            continue;
        }
        if let Some(id) = line.strip_prefix("  - Id:") {
            if let Ok(id) = id.trim().parse() {
                out.push((id, BTreeMap::new()));
            }
            section.clear();
            continue;
        }
        let Some((_, fields)) = out.last_mut() else { continue };
        let indent = line.len() - line.trim_start().len();
        let Some((key, value)) = line.trim().split_once(':') else { continue };
        let value = value.trim().trim_matches('"').to_string();
        match indent {
            4 => {
                section = if value.is_empty() { key.to_string() } else { String::new() };
                fields.insert(key.to_string(), value);
            }
            6 if !section.is_empty() && !key.starts_with('-') => {
                fields.insert(format!("{section}.{key}"), value);
            }
            _ => {}
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::entries;

    #[test]
    fn reads_fields_and_modes_by_line() {
        let text = "Body:
  - Id: 1002
    AegisName: PORING
    Level: 1
    Element: Water
    RaceGroups:
      EP172ALPHA: true
      EP172ALPHA: true
    Modes:
      Mvp: true
    Drops:
      - Item: Jellopy
        Rate: 7000
  - Id: 1003
    Level: 3
";
        let e = entries(text);
        assert_eq!(e.len(), 2);
        assert_eq!(e[0].0, 1002);
        assert_eq!(e[0].1["Element"], "Water");
        assert_eq!(e[0].1["Modes.Mvp"], "true");
        assert!(!e[0].1.contains_key("Rate"));
        assert_eq!(e[1].1["Level"], "3");
    }
}
